#!/bin/bash
# Checks to run before a commit (default), or the CI batch checks run locally
# (--level batch: crash debugging, GLES-only changes). When
# each level runs: .claude/rules/agent-workflow.md.
#
#   commit  In each --build-dir: incremental build and unit tests. Then shader
#           validation if shaders/ changed, cppcheck on the changed .cpp files
#           (compile commands from the first --build-dir), and checks on the
#           changed files: line endings kept, no em dashes, trailing
#           whitespace (warning only).
#   batch   The commit checks, plus a short smoke run (scripts/smoke.sh) with
#           each --build-dir's binary. Needs --game-dir.
#
# Changed files are compared with REF: at commit level HEAD when there are
# uncommitted changes, otherwise HEAD~1 (the commit just made); at batch level
# the point where this branch left pi-port. --base REF overrides both.
#
# cppcheck: the baseline (scripts/cppcheck-baseline.txt) is generated by CI with
# one cppcheck version. With another version locally, old findings in the
# changed files show up as "new", so the changed files are also checked as
# they were at REF, and only findings the change added fail.
#
# usage: scripts/check.sh --build-dir DIR [--build-dir DIR] [--level commit|batch]
#                         [--game-dir DIR] [--base REF] [--missions "..."] [--frames N]
#
# Exit status: 0 if every check passed, 1 otherwise, 2 for bad arguments.

set -u

LEVEL=commit
BUILD_DIRS=()
GAME_DIR=""
BASE=""
MISSIONS="mc2_01 mc2_03"
FRAMES=600
SRC_DIR="$(cd "$(dirname "$0")/.." && pwd)"

while [ $# -gt 0 ]; do
    case "$1" in
        --level)     LEVEL="$2"; shift 2 ;;
        --build-dir) BUILD_DIRS+=("$(cd "$2" 2>/dev/null && pwd || echo "$2")"); shift 2 ;;
        --game-dir)  GAME_DIR="$2"; shift 2 ;;
        --base)      BASE="$2"; shift 2 ;;
        --missions)  MISSIONS="$2"; shift 2 ;;
        --frames)    FRAMES="$2"; shift 2 ;;
        -h|--help)   sed -n '2,26p' "$0"; exit 0 ;;
        *) echo "check: unknown option $1" >&2; exit 2 ;;
    esac
done

case "$LEVEL" in
    commit|batch) ;;
    *) echo "check: --level must be commit or batch" >&2; exit 2 ;;
esac
if [ ${#BUILD_DIRS[@]} -eq 0 ]; then
    echo "check: at least one --build-dir is required" >&2; exit 2
fi
for d in "${BUILD_DIRS[@]}"; do
    [ -f "$d/build.ninja" ] || [ -f "$d/Makefile" ] || { echo "check: $d is not a configured build dir" >&2; exit 2; }
done
if [ "$LEVEL" = batch ] && { [ -z "$GAME_DIR" ] || [ ! -d "$GAME_DIR/data" ]; }; then
    echo "check: --level batch needs --game-dir with built game data" >&2; exit 2
fi

cd "$SRC_DIR" || exit 2

# Under WSL, a worktree made by Windows git points at a C:/ path that the
# Linux git cannot follow: use Windows git through interop then.
GIT=git
if ! git rev-parse --git-dir >/dev/null 2>&1; then
    if command -v git.exe >/dev/null && git.exe rev-parse --git-dir >/dev/null 2>&1; then
        GIT=git.exe
    else
        echo "check: git cannot read this checkout ($SRC_DIR)" >&2; exit 2
    fi
fi

failed=0
ok()   { echo "ok    $*"; }
warn() { echo "warn  $*"; }
fail() { echo "FAIL  $*"; failed=1; }

#---------------------------------------------------------------------------
# What changed, and against what
if [ -n "$BASE" ]; then
    REF="$BASE"
elif [ "$LEVEL" = batch ]; then
    REF=""
    for r in pi/pi-port origin/pi-port pi-port; do
        REF=$($GIT merge-base HEAD "$r" 2>/dev/null) && break
    done
    [ -n "$REF" ] || { echo "check: no pi-port branch to compare with; pass --base" >&2; exit 2; }
elif ! $GIT diff --quiet HEAD -- || [ -n "$($GIT ls-files --others --exclude-standard)" ]; then
    REF=HEAD
else
    REF=HEAD~1
fi
CHANGED=$( { $GIT diff --name-only --diff-filter=d "$REF" --; $GIT ls-files --others --exclude-standard; } | sort -u)
echo "check ($LEVEL): $(echo "$CHANGED" | grep -c .) changed file(s) against $($GIT rev-parse --short "$REF")"

#---------------------------------------------------------------------------
# Build and unit tests
for d in "${BUILD_DIRS[@]}"; do
    if cmake --build "$d" > "$d/check-build.log" 2>&1; then
        ok "build $d"
    else
        fail "build $d (log: $d/check-build.log)"
        grep -m5 -E 'error:|FAILED' "$d/check-build.log" | sed 's/^/      /'
        continue
    fi
    if ctest --test-dir "$d" --output-on-failure > "$d/check-ctest.log" 2>&1; then
        ok "unit tests $d"
    else
        fail "unit tests $d (log: $d/check-ctest.log)"
    fi
done

#---------------------------------------------------------------------------
# Shaders
if echo "$CHANGED" | grep -q '^shaders/'; then
    if ! command -v glslangValidator >/dev/null; then
        warn "shaders changed but glslangValidator is not installed: not validated"
    elif python3 scripts/validate_shaders.py > "${BUILD_DIRS[0]}/check-shaders.log" 2>&1; then
        ok "shaders"
    else
        fail "shaders (log: ${BUILD_DIRS[0]}/check-shaders.log)"
    fi
fi

#---------------------------------------------------------------------------
# cppcheck on the changed .cpp files
CPP=$(echo "$CHANGED" | grep -E '\.cpp$' | grep -vE '^(tests|thirdparty|3rdparty)/')
if [ -n "$CPP" ] && command -v cppcheck >/dev/null; then
    after=$(mktemp)
    python3 scripts/cppcheck_gate.py --build-dir "${BUILD_DIRS[0]}" --files $CPP > "$after" 2>&1
    gate=$?
    local_ver=$(cppcheck --version | awk '{print $2}')
    base_ver=$(sed -n 's/.*with Cppcheck \([0-9.]*\).*/\1/p' scripts/cppcheck-baseline.txt)
    # A gate that ran to the end prints its "cppcheck (...)" summary line.
    # Exit 2 (cppcheck failed) or a Python error (exit 1, no summary) means
    # nothing was checked, whatever the cppcheck versions.
    gate_ran() { grep -q '^cppcheck (' "$1"; }
    if [ $gate -eq 0 ]; then
        ok "cppcheck: $(grep -m1 '^cppcheck' "$after")"
    elif [ $gate -eq 2 ] || ! gate_ran "$after"; then
        fail "cppcheck gate failed: changed files not checked"
        tail -n 15 "$after" | sed 's/^/      /'
    elif [ "$local_ver" = "$base_ver" ]; then
        fail "cppcheck: $(grep -m1 '^cppcheck' "$after")"
        grep '^NEW' "$after" | sed 's/^/      /'
    else
        # Check the changed source files as they were at REF (swapped in place,
        # mtimes kept, always swapped back) and fail only on what is new.
        swap=$(mktemp -d)
        SRC=$(echo "$CHANGED" | grep -E '\.(cpp|h|hpp)$')
        restore() {
            for f in $SRC; do
                if [ -e "$swap/$f" ]; then cp -p "$swap/$f" "$f"; fi
            done
            rm -rf "$swap"
        }
        trap restore EXIT INT TERM
        BEFORE_CPP=""
        for f in $SRC; do
            mkdir -p "$swap/$(dirname "$f")" && cp -p "$f" "$swap/$f"
            if $GIT cat-file -e "$REF:$f" 2>/dev/null; then
                $GIT show "$REF:$f" > "$f"
                case "$f" in *.cpp) echo "$CPP" | grep -qx "$f" && BEFORE_CPP="$BEFORE_CPP $f" ;; esac
            fi
        done
        before=$(mktemp)
        if [ -n "$BEFORE_CPP" ]; then
            python3 scripts/cppcheck_gate.py --build-dir "${BUILD_DIRS[0]}" --files $BEFORE_CPP > "$before" 2>&1
        fi
        restore
        trap - EXIT INT TERM
        if [ -n "$BEFORE_CPP" ] && ! gate_ran "$before"; then
            fail "cppcheck gate failed on the files at $($GIT rev-parse --short "$REF"): nothing to compare with"
            tail -n 15 "$before" | sed 's/^/      /'
        else
            # Compare per-finding counts: the gate prints a surplus over the
            # baseline as "NEW ... (xN)", so going from x2 to x1 is not "added".
            added=$(awk '
                { n = 1; k = $0
                  if (match(k, / \(x[0-9]+\)$/)) { n = substr(k, RSTART + 3, RLENGTH - 4) + 0; k = substr(k, 1, RSTART - 1) } }
                FILENAME == ARGV[1] { before[k] += n; next }
                { after[k] += n }
                END { for (k in after) { d = after[k] - before[k]; if (d > 0) print k (d > 1 ? " (x" d ")" : "") } }
            ' <(grep '^NEW' "$before") <(grep '^NEW' "$after"))
            if [ -z "$added" ]; then
                ok "cppcheck: nothing new compared with $($GIT rev-parse --short "$REF") (local cppcheck $local_ver, baseline $base_ver)"
            else
                fail "cppcheck: findings added compared with $($GIT rev-parse --short "$REF")"
                echo "$added" | sed 's/^/      /'
            fi
        fi
        rm -f "$before"
    fi
    rm -f "$after"
elif [ -n "$CPP" ]; then
    warn "cppcheck not installed: changed .cpp files not checked (CI will)"
fi

#---------------------------------------------------------------------------
# Diff hygiene: line endings, em dashes, trailing whitespace
cr_count() { tr -cd '\r' | wc -c; }
for f in $CHANGED; do
    [ -f "$f" ] || continue
    grep -qI . "$f" 2>/dev/null || continue        # binary or empty
    now_cr=$(cr_count < "$f"); now_lines=$(wc -l < "$f")
    if $GIT cat-file -e "$REF:$f" 2>/dev/null; then
        ref_cr=$($GIT show "$REF:$f" | cr_count); ref_lines=$($GIT show "$REF:$f" | wc -l)
        if [ "$ref_cr" -gt 0 ] && [ "$ref_cr" -ge "$ref_lines" ] && [ "$now_cr" -lt "$now_lines" ]; then
            fail "$f: was CRLF, now has $((now_lines - now_cr)) LF-only line(s)"
        elif [ "$ref_cr" -eq 0 ] && [ "$now_cr" -gt 0 ]; then
            fail "$f: was LF, now has $now_cr CRLF line(s)"
        fi
    elif [ "$now_cr" -gt 0 ] && [ "$now_cr" -lt "$now_lines" ]; then
        fail "$f: new file mixes CRLF and LF"
    fi
done

EM_DASH=$(printf '\xe2\x80\x94')
em=$( { $GIT diff "$REF" -- | grep '^+' | grep -v '^+++';
        for f in $($GIT ls-files --others --exclude-standard); do [ -f "$f" ] && cat "$f"; done; } |
      LC_ALL=C grep -cF "$EM_DASH")
if [ "$em" -gt 0 ]; then
    fail "$em added line(s) with an em dash (CLAUDE.md: never use it)"
else
    ok "no em dashes"
fi

ws=$($GIT -c core.whitespace=cr-at-eol,trailing-space diff --check "$REF" -- | grep -c 'trailing whitespace')
[ "$ws" -gt 0 ] && warn "$ws added line(s) with trailing whitespace"

#---------------------------------------------------------------------------
# Batch: short smoke run with each build
if [ "$LEVEL" = batch ]; then
    for d in "${BUILD_DIRS[@]}"; do
        if scripts/smoke.sh --game-dir "$GAME_DIR" --build-dir "$d" --missions "$MISSIONS" \
                --frames "$FRAMES" --log-dir "$d/check-smoke" > "$d/check-smoke.log" 2>&1; then
            ok "smoke $d ($MISSIONS, $FRAMES frames)"
        else
            fail "smoke $d (log: $d/check-smoke.log)"
            grep '^FAIL' "$d/check-smoke.log" | sed 's/^/      /'
        fi
    done
fi

[ $failed -eq 0 ] && echo "check ($LEVEL): all passed" || echo "check ($LEVEL): FAILED"
exit $failed
